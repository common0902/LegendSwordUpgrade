    void PMSAsciiRender(const PMSAsciiObjs& objs, int tier)
    {
        if (tier < 0 || tier >= (int)objs.swords.size()) return;

        const vector<string>& sword = objs.swords[tier];
        int lines = (int)sword.size();
        int startY = 3;
        int swordWidth = (int)sword[0].size();
        int startX = std::max(0, WIDTH / 2 - swordWidth / 2);

        const Color tierColors[] =
        {
            Color::YELLOW, // 당근 칼
            Color::WHITE, // 그냥 단검
            Color::LIGHT_VIOLET, // 장미칼
            Color::WHITE, // 중식도
            Color::LIGHT_RED, // 화염의 칼날
            Color::CYAN, // 얼음의 칼날
            Color::WHITE, // 쌍검
            Color::CYAN,
            Color::LIGHT_BLUE,
            Color::LIGHT_BLUE,
            Color::LIGHT_VIOLET,
            Color::LIGHT_VIOLET,
            Color::LIGHT_RED,  
            Color::LIGHT_RED,
            Color::LIGHT_YELLOW, 
            Color::LIGHT_YELLOW,
        };
        Color color = tierColors[tier];

        SetColor(tierColors[tier]);
        for (int i = 0; i < lines; ++i)
        {
            GotoXY(startX, startY + i);
            cout << sword[i];
        }
        SetColor();
    }
