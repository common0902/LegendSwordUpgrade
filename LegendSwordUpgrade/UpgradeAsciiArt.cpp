    Color GetSwordColor(int tier)
    {
        const Color tierColors[] =
        {
            Color::YELLOW, Color::WHITE, Color::LIGHT_VIOLET, Color::WHITE,
            Color::LIGHT_RED, Color::CYAN, Color::WHITE, Color::RED,
            Color::BLUE, Color::VIOLET, Color::SKYBLUE, Color::CYAN,
            Color::LIGHT_BLUE, Color::GRAY, Color::BLACK, Color::LIGHT_YELLOW,
            Color::LIGHT_VIOLET, Color::WHITE, Color::SKYBLUE, Color::RED,
            Color::LIGHT_RED,
        };
        if (tier < 0 || tier > 20) return Color::WHITE;
        return tierColors[tier];
    }

