    void PMSAsciiRenderSlide(const PMSAsciiObjs& objs, int tier, int offsetY)
    {
        if (tier < 0 || tier >= (int)objs.swords.size()) return;

        const vector<string>& sword = objs.swords[tier];
        int lines = (int)sword.size();
        int swordWidth = (int)sword[0].size();
        int startX = std::max(0, WIDTH / 2 - swordWidth / 2);

        int clipTop = SWORD_START_Y;
        int clipBottom = SWORD_START_Y + SWORD_HEIGHT;

        SetColor(GetSwordColor(tier));
        for (int i = 0; i < lines; ++i)
        {
            int drawY = SWORD_START_Y + i + offsetY;

            if (drawY < clipTop || drawY >= clipBottom)
                continue;

            GotoXY(startX, drawY);
            cout << sword[i];
        }
        SetColor();
    }

    void PMSAsciiRenderTwoSlide(const PMSAsciiObjs& objs, int oldTier, int newTier, int offsetY, bool isSuccess)
    {
        int oldOffset, newOffset;
        if (isSuccess)
        {
            oldOffset = offsetY;
            newOffset = offsetY - SWORD_HEIGHT;
        }
        else
        {
            oldOffset = -offsetY;
            newOffset = SWORD_HEIGHT - offsetY;
        }

        const vector<string>& oldSword = objs.swords[oldTier];
        const vector<string>& newSword = objs.swords[newTier];

        int oldWidth = (int)oldSword[0].size();
        int newWidth = (int)newSword[0].size();
        int oldStartX = std::max(0, WIDTH / 2 - oldWidth / 2);
        int newStartX = std::max(0, WIDTH / 2 - newWidth / 2);

        string blank(WIDTH, ' ');

        for (int y = 0; y < SWORD_HEIGHT + 1; ++y)
        {
            int screenY = SWORD_START_Y + y;

            int oldIdx = y - oldOffset;
            int newIdx = y - newOffset;

            GotoXY(0, screenY);

            if (newIdx >= 0 && newIdx < (int)newSword.size())
            {
                SetColor(GetSwordColor(newTier));
                cout << string(newStartX, ' ') << newSword[newIdx];
                int drawn = newStartX + (int)newSword[newIdx].size();
                if (drawn < WIDTH) cout << string(WIDTH - drawn, ' ');
            }
            else if (oldIdx >= 0 && oldIdx < (int)oldSword.size())
            {
                SetColor(GetSwordColor(oldTier));
                cout << string(oldStartX, ' ') << oldSword[oldIdx];
                int drawn = oldStartX + (int)oldSword[oldIdx].size();
                if (drawn < WIDTH) cout << string(WIDTH - drawn, ' ');
            }
            else
            {
                cout << blank;
            }
        }
        SetColor();
    }

